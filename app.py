@app.route("/")
def index():
    """Главная страница — экран с видео и превью каталога."""
    return render_template("index.html")


@app.route("/adventures")
def adventures():
    """Каталог приключений — 5 карточек."""
    return render_template("adventures.html", adventures=adventures_data)


@app.route("/apply", methods=["POST"])
def apply():
    """Приём заявок на приключения."""
    name      = request.form.get("name", "").strip()
    people    = request.form.get("people", "1")
    comment   = request.form.get("comment", "").strip()
    adventure = request.form.get("adventure", "")

    with open("applications.txt", "a", encoding="utf-8") as f:
        f.write(
            f"---\n"
            f"Приключение: {adventure}\n"
            f"Имя:          {name}\n"
            f"Человек:      {people}\n"
            f"Комментарий:  {comment}\n"
        )

    flash("Спасибо! Ваша заявка принята.")
    return redirect(request.referrer or url_for("index"))


@app.route("/adventures/<slug>")
def adventure_detail(slug):
    """Детальная страница приключения."""
    adventure = next((a for a in adventures_data if a["slug"] == slug), None)
    if adventure is None:
        abort(404)
    return render_template("adventure.html", adventure=adventure)


@app.route("/about")
def about():
    """Страница о проекте."""
    return render_template("about.html")


